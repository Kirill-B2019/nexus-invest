    public function run(): void
    {
        $dict = RefDictionary::whereHas('group', fn ($q) => $q->where('code', 'territorial'))
            ->where('code', 'regions')
            ->first();

        if (! $dict) {
            return;
        }

        $sortOrder = 10;

        // Россия как страна (первая запись)
        RefDictionaryItem::firstOrCreate(
            ['ref_dictionary_id' => $dict->id, 'code' => 'ru'],
            [
                'name' => 'Российская Федерация',
                'description' => 'Государство в целом.',
                'item_type' => 'country',
                'country_code' => self::COUNTRY_CODE,
                'sort_order' => $sortOrder++,
                'is_active' => true,
            ]
        );

        $regions = $this->getRegionsList();

        foreach ($regions as $code => $name) {
            RefDictionaryItem::firstOrCreate(
                ['ref_dictionary_id' => $dict->id, 'code' => $code],
                [
                    'name' => $name,
                    'description' => null,
                    'item_type' => 'region',
                    'country_code' => self::COUNTRY_CODE,
                    'sort_order' => $sortOrder++,
                    'is_active' => true,
                ]
            );
        }
    }

